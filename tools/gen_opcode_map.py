#!/usr/bin/env python3
"""Generate the jadx-normalised `Opcode` enum and the Dalvik-opcode -> (Opcode, index type) map
from the reference sources (`Opcode.java`, `DexOpcodes.java`, `DexInsnInfo.java`).

Usage: tools/gen_opcode_map.py [path-to-jadx-checkout]   (default ../jadx)
"""
import re, sys, pathlib

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parents[2] / "jadx")
repo = pathlib.Path(__file__).resolve().parents[1]

def camel(name):
    return "".join(p.capitalize() for p in name.lower().split("_"))

opcode_java = (root / "jadx-plugins/jadx-input-api/src/main/java/jadx/api/plugins/input/insns/Opcode.java").read_text()
body = opcode_java[opcode_java.index("{") + 1:]
names = [n for n in re.findall(r"^\s*([A-Z][A-Z0-9_]*)\s*,", body, re.M)]

dex_ops = (root / "jadx-plugins/jadx-dex-input/src/main/java/jadx/plugins/input/dex/insns/DexOpcodes.java").read_text()
values = {m.group(1): int(m.group(2), 16) for m in re.finditer(r"int (\w+) = (0x[0-9a-fA-F]+);", dex_ops)}

info = (root / "jadx-plugins/jadx-dex-input/src/main/java/jadx/plugins/input/dex/insns/DexInsnInfo.java").read_text()
entries = []
pat = re.compile(r"register(?:Payload)?\(\s*(?:arr,\s*)?DexOpcodes\.(\w+),\s*Opcode\.(\w+),\s*DexInsnFormat\.(\w+)(?:,\s*InsnIndexType\.(\w+))?\s*\)", re.S)
for m in pat.finditer(info):
    dex, op, fmt, idx = m.groups()
    entries.append((values[dex], op, idx or "NONE"))
entries.sort()

out1 = ["// @generated by tools/gen_opcode_map.py from the reference sources. Do not edit.", "",
        "/// jadx-normalised opcode (several Dalvik opcodes map to one, e.g. all `move-*` to `Move`).",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]", "pub enum Opcode {"]
out1 += [f"    {camel(n)}," for n in names]
out1 += ["}", "", "impl Opcode {", "    /// Name as printed by the reference (`ADD_INT_LIT`).", "    pub fn name(self) -> &'static str {", "        match self {"]
out1 += [f'            Opcode::{camel(n)} => "{n}",' for n in names]
out1 += ["        }", "    }", "}"]
(repo / "crates/jadx-input-api/src/opcode.rs").write_text("\n".join(out1) + "\n")

out2 = ["// @generated by tools/gen_opcode_map.py from the reference sources. Do not edit.", "",
        "use jadx_input_api::{InsnIndexType, Opcode};", "",
        "/// Dalvik opcode (or payload ident) -> jadx opcode and the kind of its index operand.",
        "pub const JADX_MAP: &[(u16, Opcode, InsnIndexType)] = &["]
for v, op, idx in entries:
    out2.append(f"    (0x{v:04x}, Opcode::{camel(op)}, InsnIndexType::{camel(idx)}),")
out2.append("];")
(repo / "crates/jadx-dex-input/src/insns/jadx_map_gen.rs").write_text("\n".join(out2) + "\n")
print(f"{len(names)} opcodes, {len(entries)} map entries")
