/// `CodegenException`
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CodegenError {
    pub msg: String,
    pub kind: ErrorKind,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ErrorKind {
    Other,
    /// The instruction needs the body of an anonymous class, which is generated by the class
    /// level code generator.
    AnonymousClass,
    /// The instruction kind is only supported in fallback mode or not supported yet.
    Unsupported,
}

impl CodegenError {
    pub fn new(msg: impl Into<String>) -> Self {
        CodegenError {
            msg: msg.into(),
            kind: ErrorKind::Other,
        }
    }

    pub fn unsupported(msg: impl Into<String>) -> Self {
        CodegenError {
            msg: msg.into(),
            kind: ErrorKind::Unsupported,
        }
    }

    pub fn anonymous() -> Self {
        CodegenError {
            msg: "anonymous class body required".into(),
            kind: ErrorKind::AnonymousClass,
        }
    }
}

impl fmt::Display for CodegenError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.msg)
    }
}

impl std::error::Error for CodegenError {}

/// `CommentsLevel`
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum CommentsLevel {
    None,
    UserOnly,
    Error,
    Warn,
    Info,
    Debug,
}

impl CommentsLevel {
    /// `filter`: a comment of level `self` is shown when `limit` is at least that level.
    pub fn filter(self, limit: CommentsLevel) -> bool {
        self <= limit
    }
}

/// `DecompilationMode`
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DecompilationMode {
    Auto,
    Restructure,
    Simple,
    Fallback,
}

/// Original instructions of a method (`MethodNode.getInstructions` in fallback mode).
pub struct FallbackCode {
    pub insns: Vec<Option<crate::model::insn::InsnNode>>,
    pub handlers: Vec<crate::model::cfg::ExceptionHandler>,
}

/// Provides the processed code of the methods of the input (decoding and the pass pipeline).
pub trait MethodLoader {
    /// Code state of method `mth` of class `cls`; methods without code get a state with only the
    /// arguments.
    fn load(&self, cls: usize, mth: usize) -> Result<crate::model::cfg::MethodCfg, String>;

    /// The original instructions of the method for the instruction dump (fallback mode):
    /// instruction array by offset and the exception handlers.
    fn fallback_code(&self, _cls: usize, _mth: usize) -> Result<FallbackCode, String> {
        Err("instructions are not available".to_string())
    }

    /// Whether the top level class has finished the pass pipeline (`ProcessState.isProcessComplete`).
    fn class_process_complete(&self, _cls: usize) -> bool {
        true
    }

    /// Line of the source code the method starts at (`0` if unknown).
    fn source_line(&self, _cls: usize, _mth: usize) -> u32 {
        0
    }
}
