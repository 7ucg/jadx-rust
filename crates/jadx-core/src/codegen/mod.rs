//! Code generation: instruction and expression level (`InsnGen`, `TypeGen`, `NameGen`,
//! `ConditionGen`, class and method helpers and the code writer).
//!
//! The generators consume the instruction trees left by the modification and shrink passes:
//! instructions that were inlined into other instructions are wrapped arguments and are
//! printed as expressions.

pub mod class_gen;
pub mod code_writer;
pub mod insn_gen;
pub mod method_gen;
pub mod name_gen;
pub mod string_utils;
pub mod type_gen;
pub mod var_names;

use std::fmt;

pub use class_gen::{ClassGen, GenEnv};
pub use code_writer::{CodeInfo, CodeWriter};
pub use insn_gen::{Flags, InsnGen};
pub use method_gen::MethodGen;
pub use name_gen::NameGen;
pub use string_utils::{IntegerFormat, StringUtils};

/// `CodegenException`
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CodegenError {
    pub msg: String,
    pub kind: ErrorKind,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ErrorKind {
    Other,
    /// The instruction needs the body of an anonymous class, which is generated by the class
    /// level code generator.
    AnonymousClass,
    /// The instruction kind is only supported in fallback mode or not supported yet.
    Unsupported,
}

impl CodegenError {
    pub fn new(msg: impl Into<String>) -> Self {
        CodegenError {
            msg: msg.into(),
            kind: ErrorKind::Other,
        }
    }

    pub fn unsupported(msg: impl Into<String>) -> Self {
        CodegenError {
            msg: msg.into(),
            kind: ErrorKind::Unsupported,
        }
    }

    pub fn anonymous() -> Self {
        CodegenError {
            msg: "anonymous class body required".into(),
            kind: ErrorKind::AnonymousClass,
        }
    }
}

impl fmt::Display for CodegenError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.msg)
    }
}

impl std::error::Error for CodegenError {}
