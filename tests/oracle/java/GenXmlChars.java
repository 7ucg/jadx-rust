import jadx.core.xmlgen.XMLChar;

/**
 * Dev tool: prints the XML name start / name character ranges of the reference character table
 * as Rust source.
 */
public class GenXmlChars {
	public static void main(String[] args) {
		System.out.println("// @generated by tests/oracle/java/GenXmlChars.java from the reference character table.");
		System.out.println("// Do not edit by hand; regenerate instead.");
		System.out.println();
		print("NAME_START", true);
		System.out.println();
		print("NAME_CHAR", false);
	}

	private static void print(String name, boolean start) {
		StringBuilder sb = new StringBuilder();
		int count = 0;
		int c = 0;
		while (c < 0x10000) {
			if (test(c, start)) {
				int end = c;
				while (end + 1 < 0x10000 && test(end + 1, start)) {
					end++;
				}
				sb.append(String.format("    (0x%04X, 0x%04X),%n", c, end));
				count++;
				c = end + 1;
			} else {
				c++;
			}
		}
		System.out.println("pub(crate) static " + name + ": [(u16, u16); " + count + "] = [");
		System.out.print(sb);
		System.out.println("];");
	}

	private static boolean test(int c, boolean start) {
		return start ? XMLChar.isNameStart(c) : XMLChar.isName(c);
	}
}
