import java.io.File;
import java.io.PrintStream;
import java.lang.reflect.Field;
import java.util.ArrayList;
import java.util.Collection;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

import jadx.api.JadxArgs;
import jadx.api.JadxDecompiler;
import jadx.api.plugins.input.data.IFieldData;
import jadx.api.plugins.input.data.IMethodData;
import jadx.api.plugins.input.data.annotations.EncodedType;
import jadx.api.plugins.input.data.impl.ListConsumer;
import jadx.api.plugins.input.data.annotations.EncodedValue;
import jadx.api.plugins.input.data.attributes.JadxAttrType;
import jadx.core.dex.attributes.AFlag;
import jadx.core.dex.attributes.AType;
import jadx.core.dex.attributes.nodes.AnonymousClassAttr;
import jadx.core.dex.attributes.nodes.InlinedAttr;
import jadx.core.dex.info.FieldInfo;
import jadx.core.dex.info.MethodInfo;
import jadx.core.dex.nodes.ClassNode;
import jadx.core.dex.nodes.FieldNode;
import jadx.core.dex.nodes.IFieldInfoRef;
import jadx.core.dex.nodes.MethodNode;
import jadx.core.dex.nodes.RootNode;

/**
 * Oracle helper: loads the input with the reference decompiler (which runs all pre decompile passes)
 * and dumps the class level state in the format of `jadx-rs pre-info` (see
 * crates/jadx-core/src/class_dump.rs).
 */
public class ClassInfoDump {
	public static void main(String[] args) throws Exception {
		JadxArgs jargs = new JadxArgs();
		jargs.setInputFile(new File(args[0]));
		jargs.setSkipResources(true);
		PrintStream out = new PrintStream(new java.io.BufferedOutputStream(System.out, 1 << 16), false, "UTF-8");
		try (JadxDecompiler jadx = new JadxDecompiler(jargs)) {
			jadx.load();
			RootNode root = jadx.getRoot();
			List<ClassNode> classes = new ArrayList<>(root.getClasses());
			classes.sort(Comparator.comparing(ClassNode::getRawName));
			for (ClassNode cls : classes) {
				if (cls.getClsData() == null) {
					// class generated by the decompiler (app resource class), not part of the input
					continue;
				}
				dumpClass(out, cls);
			}
			dumpConstStorage(out, root);
		}
		out.flush();
	}

	private static void dumpClass(PrintStream out, ClassNode cls) {
		String raw = cls.getRawName();
		AnonymousClassAttr anon = cls.get(AType.ANONYMOUS_CLASS);
		InlinedAttr inlined = cls.get(AType.INLINED);
		out.println("C " + raw
				+ " access=0x" + Integer.toHexString(cls.getAccessFlags().rawValue())
				+ " anon=" + cls.isAnonymous()
				+ " dontGenerate=" + cls.contains(AFlag.DONT_GENERATE)
				+ " inlinedIn=" + (inlined == null ? "-" : inlined.getInlineCls().getRawName())
				+ " outer=" + (anon == null ? "-" : anon.getOuterCls().getRawName())
				+ " base=" + (anon == null ? "-" : anon.getBaseType())
				+ " inline=" + (anon == null ? "-" : anon.getInlineType().name())
				+ " deps=" + clsList(cls.getDependencies())
				+ " codegenDeps=" + clsList(cls.getCodegenDeps())
				+ " useIn=" + clsList(cls.getUseIn())
				+ " useInMth=" + mthList(cls.getUseInMth())
				+ " inlined=" + clsList(cls.getInlinedClasses()));
		for (FieldNode fld : cls.getFields()) {
			if (addedByJadx(fld)) {
				continue;
			}
			out.println("F " + raw + '.' + fld.getFieldInfo().getShortId()
					+ " access=0x" + Integer.toHexString(fld.getAccessFlags().rawValue())
					+ " instFld=" + fld.contains(AFlag.INLINE_INSTANCE_FIELD)
					+ " const=" + constRepr(fld.get(JadxAttrType.CONSTANT_VALUE))
					+ " useIn=" + mthList(fld.getUseIn()));
		}
		for (MethodNode mth : cls.getMethods()) {
			List<MethodNode> used = new ArrayList<>(mth.getUsed());
			used.sort(MethodNode::compareTo);
			out.println("M " + mthId(mth)
					+ " access=0x" + Integer.toHexString(mth.getAccessFlags().rawValue())
					+ " anonCtr=" + mth.contains(AFlag.ANONYMOUS_CONSTRUCTOR)
					+ " inlineCand=" + mth.contains(AFlag.METHOD_CANDIDATE_FOR_INLINE)
					+ " self=" + mth.callsSelf()
					+ " useIn=" + mthList(mth.getUseIn())
					+ " used=" + mthList(used)
					+ " unresolved=[" + mth.getUnresolvedUsed().stream()
							.map(m -> m.getDeclClass().getRawName() + '.' + m.getShortId())
							.collect(Collectors.joining(","))
					+ "]");
		}
	}

	private static void dumpConstStorage(PrintStream out, RootNode root) throws Exception {
		List<String> lines = new ArrayList<>();
		for (Map.Entry<Object, IFieldInfoRef> e : root.getConstValues().getGlobalConstFields().entrySet()) {
			if (generated(e.getValue())) {
				continue;
			}
			lines.add("K global " + valueRepr(e.getKey()) + ' ' + fieldRefId(e.getValue()));
		}
		Field classesField = root.getConstValues().getClass().getDeclaredField("classes");
		classesField.setAccessible(true);
		Map<ClassNode, ?> classes = (Map<ClassNode, ?>) classesField.get(root.getConstValues());
		for (Map.Entry<ClassNode, ?> ce : classes.entrySet()) {
			Object storage = ce.getValue();
			Field valuesField = storage.getClass().getDeclaredField("values");
			valuesField.setAccessible(true);
			Map<Object, IFieldInfoRef> values = (Map<Object, IFieldInfoRef>) valuesField.get(storage);
			for (Map.Entry<Object, IFieldInfoRef> e : values.entrySet()) {
				if (generated(e.getValue())) {
					continue;
				}
				lines.add("K class " + ce.getKey().getRawName() + ' ' + valueRepr(e.getKey()) + ' ' + fieldRefId(e.getValue()));
			}
		}
		lines.sort(null);
		for (String l : lines) {
			out.println(l);
		}
	}

	private static boolean generated(IFieldInfoRef ref) {
		if (!(ref instanceof FieldNode)) {
			return false;
		}
		FieldNode fld = (FieldNode) ref;
		return fld.getParentClass().getClsData() == null || addedByJadx(fld);
	}

	/** Resource id fields that the decompiler adds to the app resource class. */
	private static boolean addedByJadx(FieldNode fld) {
		ListConsumer<IFieldData, String> names = new ListConsumer<>(IFieldData::getName);
		fld.getParentClass().getClsData().visitFieldsAndMethods(names, new ListConsumer<IMethodData, String>(IMethodData::toString));
		return !names.getResult().contains(fld.getName());
	}

	private static String fieldRefId(IFieldInfoRef ref) {
		FieldInfo fi = ref.getFieldInfo();
		return fi.getDeclClass().getRawName() + '.' + fi.getShortId();
	}

	private static String constRepr(EncodedValue v) {
		if (v == null || v == EncodedValue.NULL) {
			return "-";
		}
		EncodedType t = v.getType();
		switch (t) {
			case ENCODED_BOOLEAN:
			case ENCODED_BYTE:
			case ENCODED_SHORT:
			case ENCODED_CHAR:
			case ENCODED_INT:
			case ENCODED_LONG:
			case ENCODED_FLOAT:
			case ENCODED_DOUBLE:
			case ENCODED_STRING:
			case ENCODED_TYPE:
				return valueRepr(v.getValue());
			default:
				return "?" + t;
		}
	}

	private static String valueRepr(Object v) {
		if (v instanceof Boolean) {
			return "Z:" + v;
		}
		if (v instanceof Byte) {
			return "B:" + v;
		}
		if (v instanceof Short) {
			return "S:" + v;
		}
		if (v instanceof Character) {
			return "C:" + (int) (Character) v;
		}
		if (v instanceof Integer) {
			return "I:" + v;
		}
		if (v instanceof Long) {
			return "J:" + v;
		}
		if (v instanceof Float) {
			return "F:" + String.format("%08x", Float.floatToIntBits((Float) v));
		}
		if (v instanceof Double) {
			return "D:" + String.format("%016x", Double.doubleToLongBits((Double) v));
		}
		if (v instanceof String) {
			StringBuilder sb = new StringBuilder("T:");
			String s = (String) v;
			for (int i = 0; i < s.length(); i++) {
				char c = s.charAt(i);
				if (c >= 0x20 && c < 0x7f && c != '\\') {
					sb.append(c);
				} else {
					sb.append(String.format("\\u%04x", (int) c));
				}
			}
			return sb.toString();
		}
		return "?" + v;
	}

	private static String clsList(Collection<ClassNode> list) {
		return list.stream().map(ClassNode::getRawName).collect(Collectors.joining(",", "[", "]"));
	}

	private static String mthList(Collection<MethodNode> list) {
		return list.stream().map(ClassInfoDump::mthId).collect(Collectors.joining(",", "[", "]"));
	}

	private static String mthId(MethodNode m) {
		return m.getParentClass().getRawName() + '.' + m.getMethodInfo().getShortId();
	}
}
