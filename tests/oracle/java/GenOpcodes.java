import com.android.tools.smali.dexlib2.Opcode;
import com.android.tools.smali.dexlib2.ReferenceType;

/**
 * Dev tool: prints the Dalvik opcode table (value, mnemonic, format, reference types) taken from
 * the reference baksmali/dexlib2 so the Rust table cannot drift. Output is Rust source.
 */
public class GenOpcodes {
	static String ref(int t) {
		switch (t) {
			case ReferenceType.STRING: return "RefKind::String";
			case ReferenceType.TYPE: return "RefKind::Type";
			case ReferenceType.FIELD: return "RefKind::Field";
			case ReferenceType.METHOD: return "RefKind::Method";
			case ReferenceType.METHOD_PROTO: return "RefKind::Proto";
			case ReferenceType.CALL_SITE: return "RefKind::CallSite";
			case ReferenceType.METHOD_HANDLE: return "RefKind::MethodHandle";
			default: return "RefKind::None";
		}
	}

	public static void main(String[] args) {
		java.util.TreeMap<Integer, Opcode> byValue = new java.util.TreeMap<>();
		for (Opcode op : Opcode.values()) {
			if (op.odexOnly()) {
				continue;
			}
			Short v = op.apiToValueMap.get(34);
			if (v == null) {
				// ART-only opcodes (invoke-polymorphic, invoke-custom, const-method-*) are keyed by ART version
				v = op.artVersionToValueMap.get(300);
			}
			if (v == null) {
				continue;
			}
			byValue.put(v & 0xffff, op);
		}
		System.out.println("// @generated by tests/oracle/java/GenOpcodes.java from the reference dexlib2 opcode table.");
		System.out.println("// Do not edit by hand; regenerate instead.");
		System.out.println();
		System.out.println("use super::{Format, OpInfo, RefKind};");
		System.out.println();
		System.out.println("pub const OPCODES: &[OpInfo] = &[");
		for (var e : byValue.entrySet()) {
			Opcode op = e.getValue();
			System.out.printf("    OpInfo { value: 0x%04x, name: \"%s\", format: Format::%s, ref1: %s, ref2: %s, can_throw: %b, can_continue: %b },%n",
					e.getKey(), op.name, op.format.name(), ref(op.referenceType), ref(op.referenceType2), op.canThrow(), op.canContinue());
		}
		System.out.println("];");
		System.err.println("opcodes: " + byValue.size());
	}
}
