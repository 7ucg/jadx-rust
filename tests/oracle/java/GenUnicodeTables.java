/**
 * Generates `crates/jadx-core/src/codegen/unicode_tables.rs`: the code point ranges that are not
 * printable in generated code (`NameMapper.isPrintableCodePoint`), computed with the JDK the
 * reference runs on. Usage: java GenUnicodeTables > unicode_tables.rs
 */
public class GenUnicodeTables {
	private static boolean printable(int cp) {
		if (Character.isISOControl(cp)) {
			return false;
		}
		if (Character.isWhitespace(cp)) {
			return cp == ' ';
		}
		switch (Character.getType(cp)) {
			case Character.CONTROL:
			case Character.FORMAT:
			case Character.PRIVATE_USE:
			case Character.SURROGATE:
			case Character.UNASSIGNED:
				return false;
			default:
				return true;
		}
	}

	public static void main(String[] args) {
		StringBuilder sb = new StringBuilder();
		sb.append("//! Code points that are not printable in generated code (generated by\n");
		sb.append("//! `tests/oracle/java/GenUnicodeTables.java`, Unicode version of the JDK: ")
				.append(System.getProperty("java.version")).append(").\n\n");
		sb.append("/// Sorted, merged ranges `(first, last)` of non printable code points.\n");
		sb.append("pub const NON_PRINTABLE: &[(u32, u32)] = &[\n");
		int start = -1;
		for (int cp = 0; cp <= 0x10FFFF + 1; cp++) {
			boolean np = cp <= 0x10FFFF && !printable(cp);
			if (np && start < 0) {
				start = cp;
			} else if (!np && start >= 0) {
				sb.append(String.format("    (0x%x, 0x%x),\n", start, cp - 1));
				start = -1;
			}
		}
		sb.append("];\n");
		System.out.print(sb);
	}
}
